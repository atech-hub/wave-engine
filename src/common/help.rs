    println!("USAGE:");
    println!("    wave-engine <DATA> [OPTIONS]");
    println!();
    println!("ARGUMENTS:");
    println!("    DATA              Path to training data file (e.g. data/input.txt)");
    println!();
    println!("TRAINING:");
