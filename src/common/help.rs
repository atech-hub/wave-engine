    println!("    --n-head N        Number of attention heads               [default: 12]");
    println!("    --maestro-dim N   Maestro bottleneck width                [default: 16]");
    println!("    --rk4-steps N     ODE integration steps (CPU/wgpu only)   [default: 16]");
    println!("    --out-proj-groups N  Block-diagonal groups (1=dense)      [default: 6]");
    println!("    --m1 N              Multi-grid modulus 1 (must pair with --m2, coprime)");
    println!("    --m2 N              Multi-grid modulus 2 (must pair with --m1, coprime)");
    println!("    --tied-embeddings   Use harmonic wte as output decoder (zero lm_head params)");
    println!("    --lm-rank N         Low-rank lm_head factoring (0=full rank)  [default: 0]");
    println!("                        Rank 32 at 168-dim: 172K→38K params (78% saving)");
    println!("    --wave-decode       Phase coherence output decoder (85 params vs 172K)");
    println!("    --unfreeze-phases   Learn reference phases (86K params, use with --wave-decode)");
    println!();
    println!("    Common presets:");
    println!("      168-dim:   --n-bands 84   --n-head 4   (fast diagnostic model)");
    println!("      768-dim:   --n-bands 384  --n-head 12  (default)");
    println!("      4096-dim:  --n-bands 2048 --n-head 32  --out-proj-groups 32");
    println!();
    println!("    ODE coupling (linked to AGC ceiling — stronger coupling = tighter ceiling):");
    println!("    --alpha F         ODE self-phase coupling                [default: 0.1]");
    println!("    --beta F          ODE cross-phase coupling               [default: same as alpha]");
    println!("    --agc-ceiling F   AGC max threshold (auto-derived if omitted)");
    println!("      α=0.1:  ceiling = 1.77 (strong coupling, tight AGC — char-level)");
    println!("      α=0.05: ceiling = 2.51 (medium coupling — BPE)");
    println!("      α=0.01: ceiling = 5.60 (weak coupling — large models)");
    println!();
    println!("    Recommended BPE vocab per dimension:");
    println!("      168-dim:  512 vocab  (data/tokenizer_512.json)");
    println!("      384-dim:  2K-4K vocab");
    println!("      768-dim:  50K vocab  (data/tokenizer.json)");
    println!();
    println!("RESUME:");
    println!("    --resume FILE     Resume training from checkpoint.");
    println!("                      CPU/wgpu: WCHK .bin file (restores weights + Adam + RNG)");
    println!("                      Candle:   .safetensors file (restores weights only)");
    println!("    --no-curriculum   Disable progressive band curriculum (all bands from start)");
    println!("    --checkpoint-name Save checkpoint to this filename          [default: checkpoint.bin]");
    println!("    --log-name FILE   Custom training log filename (auto-derived from checkpoint name)");
    println!();
    println!("TOKENIZER:");
    println!("    --bpe             Use BPE tokenizer (GPT-2 style)");
